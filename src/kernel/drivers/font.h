static u16 console_font_row(u8 glyph, u32 row) {
    /* Continuous single-line box drawing, not disconnected tiny glyphs. */
    if (glyph == 0xc4) {
        return row == 9 || row == 10 ? 0xfff : 0;
    }
    if (glyph == 0xb3) {
        return 0x060;
    }
    if (glyph == 0xda || glyph == 0xbf || glyph == 0xc0 || glyph == 0xd9) {
        int top = glyph == 0xda || glyph == 0xbf;
        int left = glyph == 0xda || glyph == 0xc0;
        if (row == 9 || row == 10) {
            return left ? 0x07f : 0xfe0;
        }
        return (top ? row > 10 : row < 9) ? 0x060 : 0;
    }
    if (row < 3 || row >= 17) {
        return 0;
    }
    const u8* bitmap = latin_font['?' - 32];
    if (glyph >= 32 && glyph < 128) {
        bitmap = latin_font[glyph - 32];
    } else if (glyph >= 0x80 && glyph <= 0xaf) {
        bitmap = cyrillic_font[(glyph - 0x80) % 32];
    } else if (glyph >= 0xe0 && glyph <= 0xef) {
        bitmap = cyrillic_font[glyph - 0xe0 + 16];
    } else if (glyph == 0xf0 || glyph == 0xf1) {
        bitmap = cyrillic_font[32];
    }
    u8 bits = bitmap[(row - 3) / 2];
    u16 result = 0;
    for (u32 i = 0; i < 5; ++i) {
        if (bits & (1u << i)) {
            result |= 3u << (1 + i * 2);
        }
    }
    return result;
}
