#!/usr/bin/env python3
"""Export a KFS2 v2 image into a staging tree for ext2 conversion.

Usage: migrate_kfs2.py OLD_KFS2.img EXPORT_DIR
Only native file data is copied; account configuration can be regenerated by
mkfs_ext2.py when the exported tree is used with --from.
"""
import struct
import sys
from pathlib import Path

SECTOR = 512
INODES = 512
INODE_SECTORS = 128
BITMAP_SECTORS = 8
DATA_START = 1 + INODE_SECTORS + BITMAP_SECTORS
NAME = 96
MAGIC = 0x3246534B
SUPER = struct.Struct("<IIIIIIIII")
INODE = struct.Struct("<BBBBIIIIII96s")

image = Path(sys.argv[1])
out = Path(sys.argv[2])
data = image.read_bytes()


def read_inode(index):
    byte = SECTOR + index * INODE.size
    return INODE.unpack_from(data, byte)


superblock = SUPER.unpack_from(data, 0)
if superblock[0] != MAGIC or superblock[6] != INODE.size:
    raise SystemExit("not a KFS2 v2 image")

inodes = []
for i in range(INODES):
    record = read_inode(i)
    if record[0]:
        inodes.append((i, record))

paths = {}


def path_of(index):
    if index == 0:
        return "/"
    if index in paths:
        return paths[index]
    record = read_inode(index)
    name = record[10].split(b"\0", 1)[0].decode("ascii", errors="replace").lower()
    parent = path_of(record[4])
    result = (parent.rstrip("/") + "/" + name) if parent != "/" else "/" + name
    paths[index] = result
    return result


for index, _ in inodes:
    path_of(index)

out.mkdir(parents=True, exist_ok=True)
for index, record in sorted(inodes, key=lambda item: path_of(item[0]).count("/")):
    path = path_of(index)
    target = out / path.lstrip("/")
    if record[1]:
        target.mkdir(parents=True, exist_ok=True)
        continue
    target.parent.mkdir(parents=True, exist_ok=True)
    first, sectors = record[6], record[7]
    raw = data[first * SECTOR:(first + sectors) * SECTOR][:record[5]]
    target.write_bytes(raw)

print(f"migrated {len(inodes)} inodes from {image} into {out}")
